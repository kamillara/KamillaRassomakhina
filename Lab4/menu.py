"""Меню и маршрутизация выбора режима обработки через match-case."""


def show_menu() -> None:
    """Вывести пункты меню (1–3 и 0 — выход)."""
    print("\n=== Выбор режима обработки ===")
    print("1 — черновая (k = 1.0)")
    print("2 — получистовая (k = 0.85)")
    print("3 — чистовая (k = 0.7)")
    print("0 — выход")


def select_mode() -> float | None:
    """Запросить у пользователя режим обработки.

    Циклический ввод номера режима; маршрутизация только через
    match-case. При неверном пункте — сообщение об ошибке и повторный
    запрос.

    Returns:
        Коэффициент k выбранного режима или None при выходе.
    """
    while True:
        choice = input("Выберите режим (1/2/3/0): ").strip()
        match choice:
            case "1":
                return 1.0
            case "2":
                return 0.85
            case "3":
                return 0.7
            case "0":
                return None
            case _:
                print("Ошибка: такого пункта меню нет, повторите ввод.")


def mode_name(k: float) -> str:
    """Определить название режима по коэффициенту.

    Args:
        k: коэффициент режима обработки.

    Returns:
        Название режима обработки.
    """
    match k:
        case 1.0:
            return "черновая"
        case 0.85:
            return "получистовая"
        case 0.7:
            return "чистовая"
        case _:
            return "неизвестный режим"
